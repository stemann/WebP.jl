"""
    HeaderOnlyWrapperGeneration

Generator support for libwebp's header-only convenience wrappers.

The aim of this module is to avoid drift from libwebp's header-only
convenience wrappers that are not exported by the shared libraries.

`generator.jl` uses this metadata to discover wrappers from the current libwebp
headers, validate the implemented wrapper set, render
`header_only_wrappers_epilogue.jl`, and then run Clang's wrapper generation.
"""
module HeaderOnlyWrapperGeneration

using Clang
using Clang.LibClang

include(joinpath(@__DIR__, "definitions.jl"))

export known_header_only_wrapper_names,
    discover_header_only_wrapper_names,
    render_header_only_wrapper_source,
    validate_header_only_wrapper_configuration,
    write_header_only_wrapper_file

function known_header_only_wrapper_names()
    return union(
        collect(keys(FORWARDED_HEADER_ONLY_WRAPPERS)),
        collect(keys(MANUAL_HEADER_ONLY_WRAPPERS)),
    )
end

function expression_source(expr)
    return sprint(io -> Base.show_unquoted(io, Base.remove_linenums!(copy(expr))))
end

function render_forwarded_header_only_wrapper(name::AbstractString, spec)
    signature_arguments = Any[spec.arguments...]
    return :(
        function $(Symbol(name))($(signature_arguments...))
            return $(Expr(:call, spec.callee, spec.call_arguments...))
        end
    )
end

function render_header_only_wrapper(name::AbstractString)
    if haskey(FORWARDED_HEADER_ONLY_WRAPPERS, name)
        return render_forwarded_header_only_wrapper(name, FORWARDED_HEADER_ONLY_WRAPPERS[name])
    elseif haskey(MANUAL_HEADER_ONLY_WRAPPERS, name)
        return MANUAL_HEADER_ONLY_WRAPPERS[name]
    else
        error("No header-only wrapper implementation is configured for $(name)")
    end
end

function render_header_only_wrapper_source(wrapper_names::AbstractVector{<:AbstractString})
    blocks = [
        "# The header-only wrapper definitions below are generated by gen/generator.jl."
    ]
    append!(blocks, [expression_source(render_header_only_wrapper(name)) for name in wrapper_names])
    return join(blocks, "\n\n") * "\n"
end

function extract_function_name(signature)
    if signature isa Symbol
        return String(signature)
    elseif signature isa Expr
        if signature.head == :call
            return extract_function_name(signature.args[1])
        elseif signature.head == :(::)
            return extract_function_name(signature.args[1])
        elseif signature.head == :where
            return extract_function_name(signature.args[1])
        end
    end
    return nothing
end

function defined_webp_functions(expr)
    names = String[]
    function visit(node)
        if !(node isa Expr)
            return nothing
        elseif node.head == :toplevel
            foreach(visit, node.args)
        elseif node.head == :function
            name = extract_function_name(node.args[1])
            name === nothing || (startswith(name, "WebP") && push!(names, name))
        elseif node.head == :(=) && node.args[1] isa Expr && node.args[1].head == :call
            name = extract_function_name(node.args[1])
            name === nothing || (startswith(name, "WebP") && push!(names, name))
        end
        return nothing
    end
    visit(expr)
    return unique(names)
end

function validate_header_only_wrapper_configuration(discovered_names::Vector{String})
    known_names = sort(known_header_only_wrapper_names())
    discovered_sorted = sort(copy(discovered_names))
    known_names == discovered_sorted && return nothing

    missing_implementations = setdiff(discovered_sorted, known_names)
    stale_implementations = setdiff(known_names, discovered_sorted)
    messages = String[]
    isempty(missing_implementations) || push!(
        messages,
        "Missing header-only wrapper implementations for: $(join(missing_implementations, ", "))",
    )
    isempty(stale_implementations) || push!(
        messages,
        "Configured header-only wrapper implementations not found in the current headers: $(join(stale_implementations, ", "))",
    )
    error(join(messages, "\n"))
end

function discover_header_only_wrapper_signatures(headers, args)
    discovered = Dict{String, String}()
    index = Clang.Index(true)
    for header in headers
        translation_unit = Clang.parse_header(index, header, args, CXTranslationUnit_None)
        root_cursor = Clang.getTranslationUnitCursor(translation_unit)
        for cursor in Clang.search(root_cursor, CXCursor_FunctionDecl)
            cursor_spelling = Clang.spelling(cursor)
            startswith(cursor_spelling, "WebP") || continue
            Clang.isFunctionInlined(cursor) || continue
            Clang.isCursorDefinition(cursor) || continue
            discovered[cursor_spelling] = Clang.name(cursor)
        end
    end
    return discovered
end

function discover_header_only_wrapper_names(headers, args)
    return sort(collect(keys(discover_header_only_wrapper_signatures(headers, args))))
end

function write_header_only_wrapper_file(
    header_only_wrappers_path::AbstractString, wrapper_names::Vector{String}
)
    header_only_wrapper_source = render_header_only_wrapper_source(wrapper_names)
    current_source = isfile(header_only_wrappers_path) ?
        read(header_only_wrappers_path, String) : ""
    if header_only_wrapper_source != current_source
        write(header_only_wrappers_path, header_only_wrapper_source)
    end

    rendered_names = sort(defined_webp_functions(Meta.parseall(header_only_wrapper_source)))
    rendered_names == wrapper_names || error(
        "Rendered header-only wrapper definitions do not match the requested wrapper set.\nExpected: $(join(wrapper_names, ", "))\nFound: $(join(rendered_names, ", "))"
    )
    return nothing
end

end
